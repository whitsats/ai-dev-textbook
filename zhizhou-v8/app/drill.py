"""演练：**它的产物不是「通过」，是一张写着发现了什么的清单。**

这一块量的是 8.5 第三个反直觉的事实：**演练越接近「真的坏」，发现的条数越多——
而「真的坏」里最富矿的一档，恰好是平时没人走的那条路（恢复）。**

| 演练方式 | 它坏在哪 | 它发现什么 | 什么时候做 |
| --- | --- | --- | --- |
| 桌面推演（围着一张桌子问） | 什么也不坏，只问假设 | 找的是**假设里的洞**（谁的手机号没人试过、谁有权按那个按钮） | 每月一次，最便宜 |
| 注入一个故障（测试环境停一个依赖） | 在**测试环境**坏 | 代码里的分支（降级路径到底通不通） | 每次改动后 |
| 真停一个依赖（生产，几十秒） | 在**生产**真的坏 | 配置与超时（只在一条路径上设过的超时、只在一个环境里配过的开关） | 每季一次，要演练单 |
| 恢复演练（切到备份／把数据恢复回来） | 坏的是**恢复路径本身** | **最多**——因为这条路平时根本没人走 | 每半年一次，要有回滚点 |

三条纪律：

1. **判据是「发现了什么」，而不是「过了没」**：一次「一切正常」的演练不是成功的演练，
   它是**没演练到位**的强信号（要么故障没真的发生，要么监控没看这次故障）。
2. **演练的发现要分类**：属于「代码」「配置」「文档」「流程」四类里哪一类，
   决定了它进谁的排期——**全塞给工程的那一摞会烂掉**。
3. **演练要有回滚点**：恢复演练尤其如此；没有回滚点的演练是拿生产换知识。

这一块与 `slo` / `alert` 的分界：**它量的是「我们知不知道自己哪里不知道」**——
而它给出的数（发现条数、其中「文档里没写」的条数）正好是那两个模块的输入：
发现里最贵的一类就是「这件事只有一个人知道」。
"""

from __future__ import annotations

#: 四种演练 × 五问。第二列是「它坏在哪」，第四列是**发现里有多少条是文档里没写的**（口径见下）。
DRILLS: tuple[tuple[str, str, str, int, int], ...] = (
    ("桌面推演",
     "什么也不坏，只问假设",
     "假设里的洞（谁的手机号没人试过、谁有权按那个按钮）",
     3, 2),
    ("注入一个故障（测试环境）",
     "在**测试环境**坏",
     "代码里的分支：降级路径到底通不通",
     5, 3),
    ("真停一个依赖（生产 30 秒）",
     "在**生产**真的坏",
     "配置与超时：只在一条路径上设过的超时、只在一个环境里配过的开关",
     8, 6),
    ("恢复演练（切到备份并恢复）",
     "坏的是**恢复路径本身**",
     "**最多的一档**——因为这条路平时没人走",
     11, 9),
)

#: 一次「真停 Redis 30 秒」的发现清单。五列：现象、类别、严重度、**文档里写没写**、谁去修。
REDIS_DRILL: tuple[tuple[str, str, str, str, str], ...] = (
    ("两条读路径直接 500（没走降级）", "代码", "高", "**没写**——降级开关在代码里，文档只写了「有降级」", "后端"),
    ("三条路径静默变慢（每次请求多 2 秒）", "配置", "中", "**没写**——连接池超时只在那一处设过", "后端"),
    ("缓存穿透打到数据库（QPS 涨 4 倍）", "代码", "高", "**没写**——「缓存挂了要限流」这句话没人写过", "后端"),
    ("错误率面板没动（它只看 5xx）", "监控", "中", "**没写**——这就是 8.5.1 那张 SLI 表的第一行", "SRE"),
    ("值班不知道该找谁（没有升级路径）", "流程", "高", "没写", "SRE"),
    ("状态页 40 分钟才更新", "流程", "中", "**没写**——谁能改状态页没写", "SRE"),
    ("重连风暴（客户端同时重试）", "代码", "中", "**没写**——退避只在客户端写过一半", "前端"),
    ("一次误报（把空闲当故障）", "监控", "低", "写了（那条告警本来就有说明）", "SRE"),
)


def drill_table() -> tuple[tuple[str, str, str, str, str, str], ...]:
    """四种演练 × 六栏：坏在哪、发现几条、其中文档没写几条、**「没写」占几成**、什么时候做。

    这六栏**与正文那张表逐列对应**（读数脚本直接把它打出来，不再自己拼一遍）——
    两处各拼一遍，就是「同一件事写了两份，而只有一份被检查」的入口。
    「它发现什么」那一栏在散文里展开，不进这张表（表要的是条数，不是句子）。
    """
    freq = ("每月一次", "每次改动后", "每季一次（要演练单）", "每半年一次（要有回滚点）")
    out = []
    for (name, breaks, _finds, n, undocumented), f in zip(DRILLS, freq):
        out.append((
            name,
            breaks,
            f"{n} 条",
            f"{undocumented} 条",
            f"{undocumented / n * 100:.0f}%",
            f,
        ))
    return tuple(out)


def redis_findings() -> tuple[tuple[str, str, str, str, str], ...]:
    """停 Redis 那次演练的清单。**第四列是这一块最值钱的一栏**：文档没写 ＝ 只有人知道。"""
    return REDIS_DRILL


def undocumented_share() -> tuple[int, int, float]:
    """`(文档没写的条数, 全部条数, 占比)`。**这个比例才是演练的产物**，不是「通过／不通过」。"""
    missing = sum(1 for row in REDIS_DRILL if "没写" in row[3] or row[3] == "没写")
    return missing, len(REDIS_DRILL), round(missing / len(REDIS_DRILL) * 100, 1)
