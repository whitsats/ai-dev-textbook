@dataclass(frozen=True)
class Probe:
    """一个探针在某一层的现场：看到了什么、而这一格靠什么成立。"""

    layer: str
    probe: str
    outcome: str
    why: str

    @property
    def is_leak(self) -> bool:
        """这一格是不是「多看到了别人的数据」（漏）——空与看不到都不算。"""
        return "对方" in self.outcome or "全部" in self.outcome


def probes() -> tuple[Probe, ...]:
    """把 `ANSWERS` 摊成对象。**夹具与正文用同一份**——表在这里，结论也在那里。"""
    return tuple(Probe(layer, probe, outcome, why) for layer, probe, outcome, why in ANSWERS)


def leak_table() -> tuple[tuple[str, str, str], ...]:
    """逐层统计三个探针里有几个漏。**这是这一块唯一的汇总数**，而它只在应用层是 3。"""
    out = []
    for layer, _, _ in WHERE_LAYERS:
        rows = [p for p in probes() if p.layer == layer]
        leaked = [p for p in rows if p.is_leak]
        out.append((
            layer,
            f"{len(leaked)} / {len(rows)}",
            "、".join(p.probe for p in leaked) if leaked else "一个都不漏",
        ))
    return tuple(out)


