def vector_choice(tenants: int, bulk_import: bool) -> tuple[str, str]:
    """按租户数与「要不要批量导入」选一条（返回：策略，理由）。**两个输入都是产品决定，不是技术参数**。"""
    if bulk_import and tenants > 1000:
        return ("集合级 · 一集合装所有租户（按字段过滤）",
                "要批量导入而租户数又大：partition key 的「不支持批量写入」先把这条路否掉")
    if tenants > 1000:
        return ("分区级 · partition key",
                "租户数超过集合／分区上限，只剩按键分这一条")
    if tenants > 100:
        return ("分区级 · 一租户一分区",
                "中等租户数：分区够用，而「一租户一分区」比按字段过滤先筛掉无关数据")
    if tenants > 10:
        return ("集合级 · 一租户一集合",
                "租户不多：隔离换来的是「一次误查只影响一个租户」")
    return ("库级（一租户一 Database）",
            "少数大户：隔离最强，而运营代价乘上租户数仍然划算")
