"""多租户：**「谁能看到谁的什么」是一个架构问题，而它的默认答案是错的。**

这一块量的是 8.4 第一个反直觉的事实：**隔离不是一道门，是一个默认值**——
你不选，它就等于「谁都看得到」。四件事撑起这一块（出处见 `REFERENCES.md` 第 8 篇）：

1. **行安全的默认方向是拒绝，而绕过它的路子有三条**：表上开启行策略之后，
   所有正常访问都**必须被策略允许**；「没有任何策略」等于默认拒绝。
   但**表属主默认绕过**（要 `FORCE ROW LEVEL SECURITY` 才受约束）、超级用户与
   `BYPASSRLS` 角色绕过、而 `TRUNCATE`／`REFERENCES` 这类整表操作**本来就不受约束**。
   于是「我们开了 RLS」这句话单独看不能算证据——要问的是**应用连的是哪个账号**。
2. **漏法与错法是两回事，而它们出现在不同的层**：应用层忘了写 `where` → **多看到数据**（漏）；
   存储层分区键写错 → **少看到数据**（空）。前者是事故，后者是工单，而**两类检查抓的东西不一样**。
3. **向量库的隔离是同一件事的四级版本**：数据组织是 Database → Collection → Partition／
   Partition Key 三层，四级策略各自有天花板（库级：不活跃的租户白占资源；集合级：
   一集合按字段过滤，租户一多撞性能；一租户一集合，受集合数上限；分区级：一租户一分区受分区数上限，
   而 partition key 最可扩展**但不支持批量写入**）。
4. **认人不等于认租户**：鉴权解决「你是谁」，租户解决「你属于谁」——
   后者是**从前者查出来的一个属性**，而它必须每一处都用同一个来源（见 8.4.1）。

这一块与 `quota` 的分界：**它管「看得到什么」，`quota` 管「能用多少」**。
两者都在 API 边界上落地，但只在后者身上才有「数字」（8.4 的两个台账：越权与超限）。
"""

