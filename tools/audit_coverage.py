def build_rows():
    rows = []
    for part, num, title, plan, specs, note in PLAN:
        prose = bank = 0
        keys: dict[str, int] = {}
        sizes: dict[str, int] = {}     # 素材键 → 该素材总量（未计权）
        weights: dict[str, float] = {}  # 素材键 → 本章给它的计权
        for s in specs:
            d = resolve(s)
            keys.update(d)
            sizes.update(d)
            for k in d:
                weights[k] = max(weights.get(k, 0.0), float(s[2]))
            tot = sum(d.values())
            if s[0] in BANK_KINDS:
                bank += int(tot * s[2])
            else:
                prose += int(tot * s[2])
        ratio = prose / plan if plan else 0.0
        rows.append(dict(part=part, num=num, title=title, plan=plan, prose=prose,
                         bank=bank, ratio=ratio,
                         verdict=verdict(ratio, prose > 0, bank > 0),
                         note=note, keys=keys, sizes=sizes, weights=weights))
    return rows


def part_pool(rs) -> tuple[int, int]:
    """一篇的素材池：各章计权相加，但每份素材在一篇里最多算 1.0。

    这里原本是「把引用到的整份文件全加进来」，于是归给别章的部分也算进了本篇：
    第 5 篇因此显示 0.94（够用），而各章真正用得到的量只有一半。
    计权一旦改成**按节实测**，同一篇内各章的权重本来就切得开（相加不会 > 1.0），
    所以汇总只要再加一道 1.0 的闸门——它拦的正是旧值那种「0.6 ＋ 0.4 ＋ 0.3」的
    重复计入。题库（`bank:`）用同一套算法，不再拿整份题库充数。
    """
    size: dict[str, int] = {}
    total: dict[str, float] = {}
    for x in rs:
        for k, s in x["sizes"].items():
            size[k] = s
            total[k] = total.get(k, 0.0) + x["weights"].get(k, 0.0)
    prose = sum(int(s * min(1.0, total[k])) for k, s in size.items() if not k.startswith("bank:"))
    bank = sum(int(s * min(1.0, total[k])) for k, s in size.items() if k.startswith("bank:"))
    return prose, bank


