"""5.1 的四个问题：**每一类「模型答不了」各一条**，而且都留了可核对的期望。

这张表是本章的实验夹具，也是后面几章的种子——5.6 的评测集会在这里长出来。

| 编号 | 类型 | 该召回到 | 带资料后应当是 |
| --- | --- | --- | --- |
| Q1 | 私有规范（模型不可能知道） | 发布规范 | 答出四段 |
| Q2 | 私有数字（模型不可能知道） | 调用预算 | 答出 2,400 万 |
| Q3 | **同义改写（字面零重合）** | 接口约定（**实测召不回**） | 拒答 |
| Q4 | 库里没有 | 不该召回到任何片（**实测召回了噪声**） | 拒答，而实测会编 |

两条要说清的话：

1. **Q3 与 Q4 的「该拒答」是不同原因。** Q3 是**命中了知识库但换了说法**——
   资料明明在库里，是检索这一环够不着（5.3 的向量、5.4 的改写来救）；
   Q4 是**库里真的没有**——那是生成这一环的判断（5.5 的拒答来救）。
   两件事都表现为「拒答」，但修的位置完全不同；把它们并成一条，就会去修错地方。
2. **Q3 的问法是量出来的，不是挑出来的。** 第一版我写的是「写接口要带什么防重复的标识？」，
   实测它在 `接口约定#0` 上拿了 6.24 分、**召回到了**——那条「同义改写会失手」的说法当场被推翻。
   现在这一句（「用户连点两下会不会写两条记录？」）实测**一片都召回不到**，
   与目标文档的 2-gram 交集真的是 0。
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Question:
    qid: str
    kind: str
    text: str
    #: 带资料后答案里**必须出现**的片段（空串表示「不该出现某个正解」）
    expect: str
    #: 正确行为下该召回到哪份文档；`None` 表示「库里本来就没有依据」
    want_doc: str | None
    #: 期望的召回形态：`命中`（要召回得到）／`空`（应当一片都召不回）
    want_recall: str
    #: 一句话说明它在演示什么
    why: str


QUESTIONS: tuple[Question, ...] = (
    Question(
        qid="Q1",
        kind="私有规范",
        text="知舟的发布说明必须包含哪几段？",
        expect="回滚",
        want_doc="发布规范",
        want_recall="命中",
        why="模型不可能知道的公司内部规范",
    ),
    Question(
        qid="Q2",
        kind="私有数字",
        text="知舟 2026 年第三季度的月调用预算上限是多少？",
        expect="2,400",
        want_doc="调用预算",
        want_recall="命中",
        why="内部数字：没有资料时模型只会给出一个「像那么回事」的数",
    ),
    Question(
        qid="Q3",
        kind="同义改写（零重合）",
        text="用户连点两下会不会写两条记录？",
        expect="",
        want_doc="接口约定",
        want_recall="空",
        why="**资料在库里、字面够不着**：检索这一环的缺口（5.3／5.4）",
    ),
    Question(
        qid="Q4",
        kind="库里没有",
        text="知舟 2027 年的营收目标是多少？",
        expect="",
        want_doc=None,
        want_recall="空",
        why="**库里真的没有**：生成这一环的判断（5.5）；实测它反而召回了噪声",
    ),
)


def by_id(qid: str) -> Question:
    for q in QUESTIONS:
        if q.qid == qid:
            return q
    raise KeyError(qid)
